function setTextImmediately(element, value) {
  element.textContent = value;
}

function animateTextReplacement(element, value) {
  const current = element.textContent;
  if (current === value) return;
  const animationToken = String(Number(element.dataset.animationToken || 0) + 1);
  element.dataset.animationToken = animationToken;

  const outgoing = [...current];
  const outgoingStagger = Math.max(2.6, Math.min(8, 180 / Math.max(1, outgoing.length)));
  element.replaceChildren(
    ...outgoing.map((character, index) => {
      const span = document.createElement("span");
      span.className = "type-char is-removing";
      span.textContent = character;
      span.style.animationDelay = `${index * outgoingStagger}ms`;
      return span;
    }),
  );

  const removeDuration = outgoing.length * outgoingStagger + 74;
  window.setTimeout(() => {
    if (element.dataset.animationToken !== animationToken) return;
    const incoming = [...value];
    const incomingStagger = Math.max(2.6, Math.min(8, 180 / Math.max(1, incoming.length)));
    element.replaceChildren(
      ...incoming.map((character, index) => {
        const span = document.createElement("span");
        span.className = "type-char is-growing";
        span.textContent = character;
        span.style.animationDelay = `${index * incomingStagger}ms`;
        return span;
      }),
    );
  }, removeDuration);
}

